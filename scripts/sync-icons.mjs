// Copies the Tabler outline icons this app uses into public/js/icons.js.
// Tabler Icons are MIT licensed. A custom icon set replaces these later:
// change the map in public/js/catalog.js and this list, then run again.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = path.join(root, 'node_modules/@tabler/icons/icons/outline');

const names = [
  // supplies
  'circle-dot', 'device-mobile', 'vaccine-bottle', 'vaccine', 'needle', 'device-heart-monitor', 'rectangle-vertical', 'rectangle', 'spray',
  // choices for custom supplies
  'box', 'package', 'bandage', 'first-aid-kit', 'pill', 'bottle', 'battery-2', 'plug', 'scissors', 'candy',
  'apple', 'glass-full', 'milk', 'cookie', 'backpack', 'droplet', 'heart', 'star', 'square', 'circle',
  'clipboard', 'hand-sanitizer', 'thermometer', 'flask', 'sticker',
  // interface
  'volume', 'volume-off', 'arrow-left', 'chevron-right', 'check', 'x', 'settings', 'bell', 'bell-off', 'qrcode',
  'camera', 'plus', 'trash', 'list-check', 'link', 'users', 'clock', 'moon', 'school', 'refresh',
  'alert-triangle', 'alert-octagon', 'info-circle', 'share-2', 'square-plus', 'home', 'circle-check', 'calendar-event', 'sun'
];

const out = {};
for (const n of names) {
  const svg = readFileSync(path.join(src, n + '.svg'), 'utf8');
  const inner = svg
    .replace(/^[\s\S]*?<svg[\s\S]*?>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  out[n] = inner;
}
const body = `// GENERATED by scripts/sync-icons.mjs from Tabler Icons (MIT). Do not edit.
export const ICONS = ${JSON.stringify(out, null, 1)};

// Decorative by default: the text beside an icon is what gets read aloud.
export function icon(name, cls = '') {
  const inner = ICONS[name] || ICONS['square'];
  return '<svg class="ls-icon ' + cls + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + inner + '</svg>';
}
`;
writeFileSync(path.join(root, 'public/js/icons.js'), body);
console.log('icons.js written with', names.length, 'icons');
