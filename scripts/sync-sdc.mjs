// Builds public/sdc.css from the Steven Design Co. stylesheet, so this app uses the
// system's own tokens and control components and never a copy typed by hand.
// Source: portfolio-astro/storybook/src/sdc.css, which is the CSS the site ships.
// Run again after an SDC release: npm run sync:sdc
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import os from 'node:os';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const srcPath = process.argv[2] || path.join(os.homedir(), 'portfolio-astro/storybook/src/sdc.css');
let css = readFileSync(srcPath, 'utf8');
const stamp = (css.match(/GENERATED by sync-css\.mjs on ([0-9-]+)/) || [])[1] || 'unknown';
css = css.replace(/\/\*[\s\S]*?\*\//g, '');

// Split a stylesheet into its top level rules.
function rules(text) {
  const list = [];
  let depth = 0, start = 0, open = -1;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '{') { if (depth === 0) open = i; depth++; }
    else if (c === '}') {
      depth--;
      if (depth === 0) {
        list.push({ prelude: text.slice(start, open).trim(), body: text.slice(open + 1, i) });
        start = i + 1;
      }
    } else if (c === ';' && depth === 0) { start = i + 1; }
  }
  return list;
}

// The parts of the system this app uses.
const keepClass = /^\.sdc-(btn|field|select|fieldset|choice|choice-set|form-summary|form-status|display|display-3|eyebrow|u-sr-only|u-no-ring|skip-link)(?![a-z0-9])/;
const keepPlain = new Set(['*', 'html, body', 'html', 'body', ':focus-visible', ':focus:not(:focus-visible)', 'main:focus',
  '::selection', 'a', 'a:hover', 'h1, h2, h3', 'h1', 'h2', 'h3', 'p', 'img, svg', ':root', ':root[data-theme="light"]',
  ':root, :root[data-theme="light"]']);

function keep(prelude) {
  if (keepPlain.has(prelude)) return true;
  const parts = prelude.split(',').map(s => s.trim());
  return parts.every(p => keepClass.test(p));
}

const out = [];
for (const r of rules(css)) {
  if (r.prelude.startsWith('@font-face') || r.prelude.startsWith('@keyframes')) continue;
  if (r.prelude.startsWith('@media')) {
    if (/print/.test(r.prelude)) continue;
    const inner = rules(r.body).filter(x => keep(x.prelude) && x.prelude !== 'html');
    if (inner.length) out.push(`${r.prelude} {\n${inner.map(x => `  ${x.prelude} {${x.body.replace(/\s+/g, ' ')}}`).join('\n')}\n}`);
    continue;
  }
  if (r.prelude.startsWith('@')) continue;
  if (keep(r.prelude)) out.push(`${r.prelude} {${r.body.replace(/\n\t\t\t/g, '\n')}}`);
}

const head = `/* GENERATED by scripts/sync-sdc.mjs. Do not edit.
   The Steven Design Co. tokens and control components, taken from the stylesheet
   stevendesignco.com ships (snapshot dated ${stamp}). App styles live in app.css. */
@font-face { font-family: 'Inter'; font-style: normal; font-display: swap; font-weight: 400; src: url(/fonts/inter-latin-400-normal.woff2) format('woff2'); }
@font-face { font-family: 'Inter'; font-style: normal; font-display: swap; font-weight: 600; src: url(/fonts/inter-latin-600-normal.woff2) format('woff2'); }
@font-face { font-family: 'Inter'; font-style: normal; font-display: swap; font-weight: 700; src: url(/fonts/inter-latin-700-normal.woff2) format('woff2'); }
`;
writeFileSync(path.join(root, 'public/sdc.css'), head + '\n' + out.join('\n\n') + '\n');
console.log('sdc.css written:', out.length, 'rules from snapshot', stamp);
